PRAGMA auto_vacuum=FULL;
CREATE TABLE IF NOT EXISTS rooms(
 code TEXT PRIMARY KEY, title TEXT NOT NULL, hours INTEGER NOT NULL,
 created INTEGER NOT NULL, expires INTEGER NOT NULL
);
CREATE TABLE IF NOT EXISTS members(
 token TEXT PRIMARY KEY, room TEXT NOT NULL REFERENCES rooms ON DELETE CASCADE,
 nick TEXT NOT NULL, seen INTEGER NOT NULL
);
CREATE INDEX IF NOT EXISTS member_room ON members(room,seen);
CREATE TABLE IF NOT EXISTS admins(token TEXT PRIMARY KEY, expires INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS assets(
 id INTEGER PRIMARY KEY, room TEXT NOT NULL REFERENCES rooms ON DELETE CASCADE,
 name TEXT NOT NULL, kind TEXT NOT NULL, UNIQUE(room,name)
);
CREATE TABLE IF NOT EXISTS versions(
 id INTEGER PRIMARY KEY, asset INTEGER NOT NULL REFERENCES assets ON DELETE CASCADE,
 num INTEGER NOT NULL, author TEXT NOT NULL, created INTEGER NOT NULL, note TEXT NOT NULL,
 manifest TEXT NOT NULL, size INTEGER NOT NULL, lang TEXT NOT NULL DEFAULT '', UNIQUE(asset,num)
);
CREATE TABLE IF NOT EXISTS blobs(
 id INTEGER PRIMARY KEY, room TEXT NOT NULL REFERENCES rooms ON DELETE CASCADE,
 digest TEXT NOT NULL, data BLOB NOT NULL, UNIQUE(room,digest)
);
CREATE TABLE IF NOT EXISTS messages(
 id INTEGER PRIMARY KEY, room TEXT NOT NULL REFERENCES rooms ON DELETE CASCADE,
 kind TEXT NOT NULL, author TEXT NOT NULL, body TEXT NOT NULL, lang TEXT NOT NULL,
 asset INTEGER, num INTEGER, created INTEGER NOT NULL, sender TEXT
);
CREATE INDEX IF NOT EXISTS chat_room ON messages(room,id);
